#include <kpi4/protocol/estimated_position.hpp>

#include <cstring>
#include <limits>

namespace kpi4::protocol {

std::optional<EstimatedPositionResult> decode_global_position_int(
    const FrameReadResult& event) {
    if (!event.frame || event.frame->msgid != MAVLINK_MSG_ID_GLOBAL_POSITION_INT) {
        return std::nullopt;
    }
    const auto payload_length = event.frame->len;
    if (payload_length == 0 ||
        payload_length > MAVLINK_MSG_ID_GLOBAL_POSITION_INT_LEN ||
        (event.frame->magic == MAVLINK_STX_MAVLINK1 &&
         payload_length != MAVLINK_MSG_ID_GLOBAL_POSITION_INT_LEN)) {
        return EstimatedPositionResult{EstimatedPositionError::InvalidLength};
    }

    // MAVLink 2 removes zero bytes from the tail, including base fields.
    // Pad before decoding so both generated byte-swap and aligned paths agree.
    auto padded = *event.frame;
    std::memset(_MAV_PAYLOAD_NON_CONST(&padded) + payload_length, 0,
                MAVLINK_MSG_ID_GLOBAL_POSITION_INT_LEN - payload_length);
    padded.len = MAVLINK_MSG_ID_GLOBAL_POSITION_INT_LEN;
    mavlink_global_position_int_t raw{};
    mavlink_msg_global_position_int_decode(&padded, &raw);
    if (raw.lat < -900'000'000 || raw.lat > 900'000'000) {
        return EstimatedPositionResult{EstimatedPositionError::LatitudeOutOfRange};
    }
    if (raw.lon < -1'800'000'000 || raw.lon > 1'800'000'000) {
        return EstimatedPositionResult{EstimatedPositionError::LongitudeOutOfRange};
    }
    if (raw.hdg != std::numeric_limits<std::uint16_t>::max() && raw.hdg > 35'999) {
        return EstimatedPositionResult{EstimatedPositionError::HeadingOutOfRange};
    }

    std::optional<core::Degrees> heading;
    if (raw.hdg != std::numeric_limits<std::uint16_t>::max()) {
        heading = core::Degrees{static_cast<double>(raw.hdg) / 100.0};
    }

    constexpr double degrees_per_e7 = 1.0 / 10'000'000.0;
    constexpr double meters_per_millimeter = 1.0 / 1000.0;
    constexpr double meters_per_second_per_centimeter_per_second = 1.0 / 100.0;

    return EstimatedPositionResult{EstimatedPosition{
        event.channel,
        event.frame->sysid,
        event.frame->compid,
        raw.time_boot_ms,
        core::Wgs84Position{
            core::Degrees{static_cast<double>(raw.lat) * degrees_per_e7},
            core::Degrees{static_cast<double>(raw.lon) * degrees_per_e7}},
        core::Altitude{core::Meters{static_cast<double>(raw.alt) *
                                    meters_per_millimeter},
                       core::AltitudeReference::mean_sea_level},
        core::Altitude{core::Meters{static_cast<double>(raw.relative_alt) *
                                    meters_per_millimeter},
                       core::AltitudeReference::relative_to_home},
        core::NorthEastVelocity{
            core::MetersPerSecond{static_cast<double>(raw.vx) *
                                  meters_per_second_per_centimeter_per_second},
            core::MetersPerSecond{static_cast<double>(raw.vy) *
                                  meters_per_second_per_centimeter_per_second}},
        core::MetersPerSecond{static_cast<double>(raw.vz) *
                              meters_per_second_per_centimeter_per_second},
        heading,
    }};
}

}  // namespace kpi4::protocol
